export const messages: Record<PanelLocale, LocaleMessages> = { ru, en, uk, pl };

export function translateMessage(
  locale: PanelLocale,
  key: LocaleMessageKey,
  parameters: Record<string, string | number> = {},
): string {
  return messages[locale][key].replace(
    /\{([A-Za-z0-9_]+)\}/g,
    (match, name: string) =>
      Object.hasOwn(parameters, name) ? String(parameters[name]) : match,
  );
}

export function isPanelLocale(value: unknown): value is PanelLocale {
  return (
    typeof value === "string" && panelLocales.includes(value as PanelLocale)
  );
}
